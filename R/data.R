#'
#' @format A data frame with 240 rows and 7 columns: `item` (column name in
#'   the response data), `trait` (`H`, `E`, `X`, `A`, `C` or `O`),
#'   `trait_label` (for example `Honesty-Humility`), `facet` and
#'   `facet_label` (for example `HSinc` and `Sincerity`), `statement` (the
#'   item text) and `reverse` (`TRUE` for reverse-keyed items).
