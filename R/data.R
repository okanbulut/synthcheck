#' HEXACO responses of real people, for checking synthetic respondents
#'
#' Answers of 17,874 adults from Canada, Great Britain and the United States
#' to the 240 items of the IPIP-HEXACO, a public-domain measure of the six
#' HEXACO personality traits (Ashton, Lee & Goldberg, 2007). The respondents
#' were volunteers who took the inventory online through the Open-Source
#' Psychometrics Project, which posted the data in 2014. They are the real
#' comparison sample for the language model responses in [hexaco_llm].
#'
#' Answers are on a 7-point scale (1 = strongly disagree, 2 = disagree,
#' 3 = slightly disagree, 4 = neutral, 5 = slightly agree, 6 = agree,
#' 7 = strongly agree) and are stored as given: Reverse-keyed items are
#' **not** reversed. Use `hexaco_items$reverse` and `8 - x` before scoring.
#' The 117 answers outside 1 to 7 in the original file (coded 0) are `NA`.
#'
#' @format A data frame with 17,874 rows (one per respondent) and 241
#'   columns: `country` (factor: `Canada` (1,708), `Great Britain` (1,149) or
#'   `United States` (15,017)) and the 240 items, named as in
#'   `hexaco_items$item` (for example `HSinc1`, the first Sincerity item).
#' @source Open-Source Psychometrics Project,
#'   <http://openpsychometrics.org/_rawdata/> (HEXACO data, 2014; 22,786
#'   respondents from all countries). The script is `data-raw/hexaco.R` in
#'   the package's GitHub repository.
#' @references Ashton, M. C., Lee, K., & Goldberg, L. R. (2007). The
#'   IPIP-HEXACO scales: An alternative, public-domain measure of the
#'   personality constructs in the HEXACO model. *Personality and Individual
#'   Differences, 42*(8), 1515-1526. \doi{10.1016/j.paid.2006.10.027}
#' @seealso [hexaco_llm] for the language model answers to the same items,
#'   [hexaco_items] for the items and their keys, [synthetic_coverage()] and
#'   [authenticity_benchmark()].
#' @examples
#' table(hexaco_real$country)
#' # Honesty-Humility scores, with reverse-keyed items reversed
#' h <- hexaco_items$item[hexaco_items$trait == "H"]
#' x <- hexaco_real[h]
#' rev <- intersect(h, hexaco_items$item[hexaco_items$reverse])
#' x[rev] <- 8 - x[rev]
#' tapply(rowMeans(x, na.rm = TRUE), hexaco_real$country, mean)
"hexaco_real"

#' HEXACO responses generated by six language models
#'
#' 89,597 synthetic respondents to the 240 IPIP-HEXACO items, generated by
#' six large language models for Canada, Great Britain and the United
#' States, in 10 independent attempts of about 500 respondents per model and
#' country. They pair with the real answers in [hexaco_real].
#'
#' Each respondent was generated in its own conversation. The model was
#' asked to simulate one adult drawn at random from the general adult
#' population of the named country (not an average or typical person), to
#' answer as that person rather than as an AI or a socially desirable person,
#' and to use the full range of the scale. No demographic details were given,
#' so the country was the only part of the prompt that changed. The items
#' were shown in their original order in six blocks of 40, at temperature
#' 1.0.
#'
#' | `model` | Checkpoint or model ID | Developer | Generated |
#' |---|---|---|---|
#' | Gemma 4 26B | google/gemma-4-26B-A4B-it (FP8) | Google | July to September 2026 |
#' | GPT-OSS-120B | openai/gpt-oss-120b (MXFP4) | OpenAI | July to September 2026 |
#' | Qwen 3.8 27B | Qwen/Qwen3.8-27B-FP8 | Alibaba | July to September 2026 |
#' | Qwen 3.5 122B | Qwen/Qwen3.5-122B-A10B-FP8 | Alibaba | July to September 2026 |
#' | Claude Haiku 5.5 | claude-haiku-5-5 | Anthropic | November 2026 |
#' | GPT-4.1 mini | gpt-4.1-mini | OpenAI | November 2026 |
#'
#' The four open-weight models ran on the Aleph Inference Gateway of the
#' Vulcan cluster (Digital Research Alliance of Canada). Claude Haiku 5.5
#' ran through the Anthropic API at its default temperature (1.0) with
#' thinking turned off; that API takes no sampling seed. GPT-4.1 mini is
#' the model ID logged in the files that were supplied for ChatGPT.
#'
#' Rows logged under another model were removed: 379 rows in the Qwen 3.8
#' 27B files and 11 rows (logged as `gpt-4o-2024-08-06`) in the GPT-4.1 mini
#' files. One GPT-4.1 mini attempt for the United States has 497
#' respondents. So a few attempts have fewer than 500 respondents. As in
#' [hexaco_real], answers are stored as given (1 to 7), with reverse-keyed
#' items not reversed. No answer is missing.
#'
#' @format A data frame with 89,597 rows (one per synthetic respondent) and
#'   243 columns: `model` (factor, the six models above), `country` (factor:
#'   `Canada`, `Great Britain` or `United States`), `attempt` (1 to 10) and
#'   the 240 items, named as in `hexaco_items$item`.
#' @source Generated by Okan Bulut. The script is `data-raw/hexaco.R` in the
#'   package's GitHub repository.
#' @seealso [hexaco_real], [hexaco_items], [synthetic_coverage()],
#'   [authenticity_benchmark()] and the article
#'   [Checking synthetic respondents](https://www.okanbulut.com/mirtverse/articles/synthetic-coverage.html).
#' @examples
#' with(hexaco_llm, table(model, country))
#' # one list per model, one data frame per attempt: the shape that
#' # synthetic_coverage() and authenticity_benchmark() take
#' h <- hexaco_items$item[hexaco_items$trait == "H"]
#' ca <- hexaco_llm[hexaco_llm$country == "Canada", ]
#' syn <- lapply(split(ca, ca$model), function(m) split(m[h], m$attempt))
#' lengths(syn)
"hexaco_llm"

